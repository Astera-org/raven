export const pubsCreateCommand: CommandSpec = {
  name: "create",
  group: "pubs",
  authLevel: "required",
  routes: [
    { method: "post", path: "/publications" },
    { method: "post", path: "/publications/id/{id}/draft/media-assets" },
    { method: "put", path: "/publications/id/{id}/draft/bibliography" },
    { method: "put", path: "/publications/id/{id}/draft/content" },
  ],
  register(parent, runtime) {
    parent
      .command("create")
      .description("Create a publication draft from a MyST document")
      .argument("<path>", "A .md file, or a MyST project directory (myst.yml)")
      .option(
        "--slug <slug>",
        "Slug for the publication (default: from the title)"
      )
      .option(
        "--org <org>",
        "Attach to an organization (slug or ID); repeat for several, in priority order",
        (value: string, previous: string[]) => [...previous, value],
        [] as string[]
      )
      .option(
        "--page <file>",
        "The article to use in a project with several pages"
      )
      .option("--dry-run", "Check the document without creating anything")
      .addHelpText(
        "after",
        [
          "",
          "The document's frontmatter sets the title, subtitle, abstract,",
          "license (an SPDX ID), keywords and DOI. For a project, the page",
          "inherits fields such as license and keywords from myst.yml.",
          "",
          "The publication is linked to the document in .raven/publications.json,",
          "so `raven pubs push` can update it. Local images are uploaded to the",
          "new draft and their paths replaced with the uploaded URLs; the file",
          "itself isn't changed. `{include}` and `{literalinclude}` of local",
          "files aren't supported.",
          "",
          "Examples:",
          "  raven pubs create paper.md",
          "  raven pubs create . --page paper.md --slug corvid-cognition",
          "  raven pubs create paper.md --org vanderbilt --dry-run",
        ].join("\n")
      )
      .action(async (path, options, command) => {
        const input = await readPublicationInput(path, { page: options.page });
        const local = await readLocalMediaFiles(input);
        const bibliography = await readBibliographyFiles(input);
        const slug = options.slug;

        if (options.dryRun) {
          const { output } = createLocalContext(command, runtime);
          input.warnings.forEach((warning) => output.warn(warning));
          const plan = {
            dryRun: true,
            file: input.linkPath,
            bytes: Buffer.byteLength(input.source),
            slug: slug ?? null,
            orgs: options.org,
            uploads: local.files.map(({ display, data, lines }) => ({
              file: display,
              bytes: data.byteLength,
              lines,
            })),
            bibliography: bibliographyPlan(bibliography),
          };
          output.data(plan, () =>
            [
              `Would create a publication from ${input.linkPath}.`,
              formatFields([
                ["Size", `${plan.bytes} bytes`],
                ["Slug", slug ?? "generated by the server"],
                ["Orgs", options.org.join(", ") || "-"],
              ]),
              ...formatUploads(local.files),
              ...formatBibliography(bibliography),
            ].join("\n")
          );
          return;
        }

        const { output, profile, api } = await createContext(
          command,
          pubsCreateCommand.authLevel,
          runtime
        );
        input.warnings.forEach((warning) => output.warn(warning));
        const links = await LinkFile.read(input.linkRoot);
        const existing = links.get(profile.apiUrl, input.linkPath);
        if (existing) {
          throw new CliError(
            `${input.linkPath} is already linked to publication ${existing.slug} on ${profile.apiUrl}; use \`raven pubs push\` to update it`,
            ExitCode.Usage
          );
        }

        const orgs = options.org.map(orgReference);
        const created = await unwrapResponse(profile.apiUrl, () =>
          api.POST("/publications", {
            body: {
              importDocument: {
                format: "mystmd",
                body: input.source,
                filename: input.filename,
              },
              slug,
              orgs: orgs.length > 0 ? orgs : undefined,
            },
          })
        );
        const createdEtag = created.response.headers.get("ETag");
        if (!createdEtag) {
          throw new CliError(
            `the server created publication ${created.data.slug} but sent no ETag; link it with \`raven pubs push --slug ${created.data.slug}\``,
            ExitCode.Server
          );
        }
        await links.set(profile.apiUrl, input.linkPath, {
          id: created.data.publicationId,
          slug: created.data.slug,
          etag: createdEtag,
        });

        let data = created.data;
        let etag = createdEtag;
        let uploads: UploadedMedia["uploads"] = [];
        // The create was made from the document as written, so with a
        // bibliography its response warns about every citation of it. Sending
        // the files and the document again replaces those warnings.
        if (local.files.length > 0 || bibliography.length > 0) {
          ({ data, etag, uploads } = await pushWithMedia({
            api,
            apiUrl: profile.apiUrl,
            input,
            local,
            bibliography,
            publicationId: data.publicationId,
            slug: data.slug,
            etag,
            output,
            // The bibliography write moves the draft's ETag, so the link
            // keeps up with it: if the content write then fails, the push
            // that finishes the job doesn't see its own write as a conflict.
            onBibliographyStored: (storedEtag) =>
              links.set(profile.apiUrl, input.linkPath, {
                id: created.data.publicationId,
                slug: created.data.slug,
                etag: storedEtag,
              }),
          }));
          await links.set(profile.apiUrl, input.linkPath, {
            id: data.publicationId,
            slug: data.slug,
            etag,
          });
        }

        warningIssues(data.validationErrors).forEach((issue) =>
          output.warn(formatIssue(issue))
        );
        const linkFile = displayPath(links.path);
        output.data(
          {
            ...data,
            etag,
            linkFile,
            uploads,
            bibliography: bibliographyPlan(bibliography),
          },
          () =>
            [
              `Created publication ${data.slug} (${data.publicationId}).`,
              `Linked ${input.linkPath} in ${linkFile}.`,
              formatValidationErrors(data.validationErrors),
              ...editLinkLines(data.links),
            ].join("\n")
        );
      });
  },
};

/**
 * Uploads the document's media and stores its bibliography on the draft just
 * created, then replaces the draft with the document pointing at the
 * uploaded URLs, so the issues reported are the last write's. A failure is
 * explained by what the draft is still missing.
 */
async function pushWithMedia({
  api,
  apiUrl,
  input,
  local,
  bibliography,
  publicationId,
  slug,
  etag,
  output,
  onBibliographyStored,
}: {
  api: ApiClient;
  apiUrl: string;
  input: PublicationInput;
  local: LocalMediaFiles;
  bibliography: BibliographyFile[];
  publicationId: string;
  slug: string;
  etag: string;
  output: Output;
  onBibliographyStored: (etag: string) => Promise<void>;
}) {
  let bibliographyStored = false;
  const explain = (error: unknown) =>
    explainPartialCreate(error, {
      file: input.linkPath,
      slug,
      hasMedia: local.files.length > 0,
      missingBibliography: bibliography.length > 0 && !bibliographyStored,
    });

  const { urls, uploads } = await uploadMediaFiles({
    api,
    apiUrl,
    publicationId,
    files: local.files,
    output,
  }).catch((error: unknown) => {
    throw explain(error);
  });
  let ifMatch = etag;
  // The draft was just created, so it has none: only send files there are.
  if (bibliography.length > 0) {
    const stored = await putDraftBibliography(api, apiUrl, {
      id: publicationId,
      slug,
      files: bibliography,
      ifMatch: etag,
    }).catch((error: unknown) => {
      throw explain(error);
    });
    bibliographyStored = true;
    ifMatch = stored.etag;
    stored.warnings.forEach(({ message }) => output.warn(message));
    await onBibliographyStored(ifMatch).catch((error: unknown) => {
      throw explainUnsavedEtag(error, {
        file: input.linkPath,
        slug,
        hasMedia: local.files.length > 0,
      });
    });
  }
  const { data, response } = await putDraftContent(api, apiUrl, {
    id: publicationId,
    filename: input.filename,
    source: rewriteMedia(input.source, local.media, urls),
    ifMatch,
  }).catch((error: unknown) => {
    throw explain(error);
  });
  const newEtag = response.headers.get("ETag");
  if (!newEtag) {
    throw new CliError(
      `the server updated ${data.slug} but sent no ETag`,
      ExitCode.Server
    );
  }
  return { data, etag: newEtag, uploads };
}

/**
 * The bibliography write committed, but its ETag couldn't be saved, so the
 * link still has the create's and the document wasn't sent again: a plain
 * `push` would report this command's own write as a conflict.
 */
function explainUnsavedEtag(
  error: unknown,
  { file, slug, hasMedia }: { file: string; slug: string; hasMedia: boolean }
): CliError {
  const media = hasMedia ? ", so it still points at the local media paths" : "";
  return new CliError(
    [
      `could not save the draft's new ETag: ${error instanceof Error ? error.message : String(error)}`,
      `Publication ${slug} was created and linked to ${file}, and its bibliography stored, but its document wasn't sent again${media}. Fix the link file, then run \`raven pubs push --force\` with the same arguments to finish.`,
    ].join("\n"),
    error instanceof CliError ? error.exitCode : ExitCode.General,
    error instanceof CliError ? error.details : undefined
  );
}

/**
 * The publication exists and is linked, so `push` can finish the job. Until
 * the content write succeeds, the draft is the document as written, so it
 * points at the local media paths; the bibliography is missing until its
 * write succeeds.
 */
function explainPartialCreate(
  error: unknown,
  {
    file,
    slug,
    hasMedia,
    missingBibliography,
  }: {
    file: string;
    slug: string;
    hasMedia: boolean;
    missingBibliography: boolean;
  }
): unknown {
  if (!(error instanceof CliError)) return error;
  const missing = [
    ...(hasMedia ? ["the uploaded media (it still has the local paths)"] : []),
    ...(missingBibliography ? ["its bibliography"] : []),
  ];
  const state =
    missing.length > 0
      ? `but its draft doesn't have ${missing.join(" or ")} yet`
      : "but the document wasn't sent again after its bibliography";
  return new CliError(
    [
      error.message,
      `Publication ${slug} was created and linked to ${file}, ${state}. Run \`raven pubs push\` with the same arguments to finish.`,
    ].join("\n"),
    error.exitCode,
    error.details
  );
}

const ULID = /^[0-9A-HJKMNP-TV-Z]{26}$/i;

/** The server looks orgs up by ID or slug, and rejects unknown ones. */
function orgReference(org: string): { orgId: string } | { orgSlug: string } {
  return ULID.test(org) ? { orgId: org } : { orgSlug: org };
}
