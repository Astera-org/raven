/**
 * Regenerates the committed v1 API spec and types:
 *
 *   pnpm generate:api                      # from http://localhost:7001
 *   pnpm generate:api https://api.staging.thestacks.org
 *   pnpm generate:api ./openapi.json       # from a saved spec file
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";
import { format, resolveConfig } from "prettier";

const apiDir = join(dirname(fileURLToPath(import.meta.url)), "../src/api");
const specPath = join(apiDir, "openapi.json");
const typesPath = join(apiDir, "v1.d.ts");

const source =
  process.argv[2] ?? process.env.RAVEN_API_URL ?? "http://localhost:7001";

async function loadSpec(): Promise<unknown> {
  if (!/^https?:\/\//.test(source)) {
    return JSON.parse(await readFile(source, "utf8"));
  }
  const url = `${source.replace(/\/+$/, "").replace(/\/api$/, "")}/api/v1/openapi.json`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`GET ${url} failed with status ${response.status}`);
  }
  return response.json();
}

async function writeFormatted(path: string, text: string): Promise<void> {
  const options = await resolveConfig(path);
  await writeFile(path, await format(text, { ...options, filepath: path }));
}

const spec = await loadSpec();
// The servers list reflects whichever deployment the spec was fetched from.
const { servers: _servers, ...portableSpec } = spec as Record<string, unknown>;

const header = [
  "/**",
  " * Generated by `pnpm generate:api` from the v1 OpenAPI spec. Do not edit.",
  " */",
  "",
].join("\n");
const types = astToString(await openapiTS(portableSpec as unknown as OpenAPI3));

await writeFormatted(specPath, JSON.stringify(portableSpec, null, 2));
await writeFormatted(typesPath, `${header}${types}`);

process.stdout.write(`Wrote ${specPath}\nWrote ${typesPath}\n`);
